export type RequestType =
  | "Exterior Images"
  | "Interior Images"
  | "Additional Images"
  | "Product Images"
  | "Cover Image"
  | "Profile Image"
  | "Phone Number"
  | "Additional Phone Numbers"
  | "Store Name"
  | "Business Description"
  | "Address";

export interface RequestCardImage {
  id: string;
  url: string;
  title?: string;
  isNew?: boolean;
  status?: "approved" | "rejected" | "pending";
}

export interface RequestCard {
  id: string;
  type: RequestType;
  date: string;
  lastUpdatedDate?: string;
  raisedBy: string;
  status: "Pending" | "Approved" | "Rejected" | "Partially Approved" | "Withdrawn";
  isUpdated?: boolean;
  statusInfo?: string;
  managerComment?: string;
  approverComment?: string;
  oldValue?: string;
  newValue?: string;
  phoneNumbers?: string[];
  images?: RequestCardImage[];
}

export interface StoreLocationRequest {
  id: string;
  storeName: string;
  storeCode: string;
  address: string;
  managerName: string;
  totalRequests: number;
  pending: number;
  approved: number;
  rejected: number;
  withdrawn: number;
  lastRequestDate: string;
  lastStatus: "Pending" | "Approved" | "Rejected" | "Partially Approved" | "Withdrawn";
  requestCards: RequestCard[];
}

export interface StoreManagerItem {
  id: string;
  firstName: string;
  lastName: string;
  email: string;
  mobile: string;
  status: "Active" | "Inactive";
  loginStatus: "Invited" | "Active" | "Pending";
  lastSeen: string;
  lastLoginIp: string;
  lastModifiedAt: string;
  accessibleLocations: { id: string; storeName: string; storeCode: string }[];
}

